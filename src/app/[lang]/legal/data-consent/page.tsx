type SupportedLang = keyof typeof content;

function isSupportedLang(lang: string): lang is SupportedLang {
  return lang in content;
}

export default async function DataConsentPage({ params }: Props) {
  const { lang } = await params;
  if (!hasLocale(lang) || !isSupportedLang(lang)) notFound();

  const doc = content[lang];

  return (
    <main className="min-h-screen bg-slate-50 py-12 px-4">
      <div className="mx-auto max-w-3xl">

        {/* Header card */}
        <div className="mb-8 rounded-2xl border border-brand-100 bg-white p-8 shadow-sm">
          <div className="mb-2 inline-flex items-center gap-2 rounded-full bg-brand-50 px-3 py-1 text-xs font-semibold text-brand-700">
            {doc.version}
          </div>
          <h1 className="mt-2 text-2xl font-extrabold text-slate-900 leading-tight">{doc.title}</h1>
          <p className="mt-1 text-sm text-slate-500">{doc.lastUpdated}</p>
        </div>

        {/* Sections */}
        <div className="space-y-4">
          {doc.sections.map((section) => (
            <div
              key={section.heading}
              className="rounded-2xl border border-slate-200 bg-white p-6 shadow-sm"
            >
              <h2 className="mb-3 text-base font-bold text-slate-900">{section.heading}</h2>
              <p className="text-sm leading-relaxed text-slate-600">{section.body}</p>
            </div>
          ))}
        </div>

        {/* Language switcher */}
        <div className="mt-8 flex flex-wrap gap-2">
          {(["uk", "en", "ru"] as const).map((l) => (
            <Link
              key={l}
              href={`/${l}/legal/data-consent`}
              className={`rounded-lg border px-4 py-2 text-sm font-medium transition-colors ${
                l === lang
                  ? "border-brand-300 bg-brand-50 text-brand-700"
                  : "border-slate-200 bg-white text-slate-600 hover:bg-slate-50"
              }`}
            >
              {{ uk: "Українська", en: "English", ru: "Русский" }[l]}
            </Link>
          ))}
        </div>

        {/* Back link */}
        <div className="mt-6">
          <Link href={`/${lang}/auth/register`} className="text-sm font-medium text-brand-600 hover:text-brand-700 hover:underline">
            ← {lang === "uk" ? "Повернутись до реєстрації" : lang === "ru" ? "Вернуться к регистрации" : "Back to registration"}
          </Link>
        </div>
      </div>
    </main>
  );
}
